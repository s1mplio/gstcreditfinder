"""Database connection: Postgres when DATABASE_URL is set, else a SQLite file.

Hosted (Vercel) the disk doesn't persist, so data lives in Postgres
(e.g. Neon). Locally and in tests a SQLite file needs no setup.

Queries are written once, with '?' placeholders and SQL both engines
accept (ON CONFLICT, RETURNING); the Postgres side translates '?' to
'%s'. Rows support row["column"] on both.
"""

import os
import sqlite3
import threading
from contextlib import contextmanager
from pathlib import Path

try:
    import psycopg
    from psycopg.rows import dict_row
except ImportError:  # only needed with DATABASE_URL
    psycopg = None

DATABASE_URL = os.getenv("DATABASE_URL", "")
DB_PATH = Path(os.getenv("GST_DB", Path(__file__).resolve().parents[1] / "data" / "gst_credit_finder.db"))

IntegrityError = (sqlite3.IntegrityError,) + ((psycopg.IntegrityError,) if psycopg else ())

SCHEMA = """
CREATE TABLE IF NOT EXISTS users (
    id {id},
    name TEXT NOT NULL,
    login TEXT NOT NULL UNIQUE,
    password_hash TEXT NOT NULL,
    role TEXT NOT NULL,
    created DOUBLE PRECISION NOT NULL,
    notify INTEGER NOT NULL DEFAULT 1
);

CREATE TABLE IF NOT EXISTS sessions (
    token_hash TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    expires DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS businesses (
    id {id},
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    gstin TEXT NOT NULL DEFAULT '',
    created DOUBLE PRECISION NOT NULL
);

CREATE TABLE IF NOT EXISTS checks (
    id {id},
    business_id BIGINT NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
    created DOUBLE PRECISION NOT NULL,
    period_text TEXT NOT NULL,
    total_at_risk DOUBLE PRECISION NOT NULL,
    claimable DOUBLE PRECISION NOT NULL,
    recovered DOUBLE PRECISION NOT NULL DEFAULT 0,
    result_json TEXT NOT NULL,
    report {blob} NOT NULL
);

CREATE TABLE IF NOT EXISTS reminders (
    business_id BIGINT NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
    supplier_gstin TEXT NOT NULL,
    status TEXT NOT NULL,
    updated DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (business_id, supplier_gstin)
);

CREATE TABLE IF NOT EXISTS password_resets (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    code_hash TEXT NOT NULL,
    created DOUBLE PRECISION NOT NULL,
    expires DOUBLE PRECISION NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0
);

-- Monthly "your GSTR-2B is ready" messages already sent.
CREATE TABLE IF NOT EXISTS nudges (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    period TEXT NOT NULL,
    sent DOUBLE PRECISION NOT NULL,
    PRIMARY KEY (user_id, period)
);

-- Purchase bills entered in the app (amounts as exact decimal text).
CREATE TABLE IF NOT EXISTS bills (
    id {id},
    business_id BIGINT NOT NULL REFERENCES businesses(id) ON DELETE CASCADE,
    supplier_gstin TEXT NOT NULL,
    supplier_name TEXT NOT NULL DEFAULT '',
    invoice_number TEXT NOT NULL,
    invoice_key TEXT NOT NULL,
    invoice_date TEXT NOT NULL,
    taxable_value TEXT NOT NULL,
    igst TEXT NOT NULL,
    cgst TEXT NOT NULL,
    sgst TEXT NOT NULL,
    cess TEXT NOT NULL,
    invoice_value TEXT NOT NULL,
    created DOUBLE PRECISION NOT NULL,
    UNIQUE (business_id, supplier_gstin, invoice_key)
);

-- Failed logins and reset requests, for throttling. Kept in the
-- database because serverless instances don't share memory.
CREATE TABLE IF NOT EXISTS attempts (
    key TEXT NOT NULL,
    at DOUBLE PRECISION NOT NULL
);

CREATE INDEX IF NOT EXISTS bills_by_month ON bills(business_id, invoice_date);
CREATE INDEX IF NOT EXISTS checks_by_business ON checks(business_id, created);
CREATE INDEX IF NOT EXISTS businesses_by_user ON businesses(user_id);
CREATE INDEX IF NOT EXISTS attempts_by_key ON attempts(key, at);
"""

SQLITE_TYPES = {"id": "INTEGER PRIMARY KEY", "blob": "BLOB"}
POSTGRES_TYPES = {"id": "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", "blob": "BYTEA"}

# Columns added to SQLite files created by earlier versions.
SQLITE_MIGRATIONS = [
    ("users", "notify", "INTEGER NOT NULL DEFAULT 1"),
]

_ready = set()
_ready_lock = threading.Lock()


def is_postgres() -> bool:
    return bool(DATABASE_URL)


class Connection:
    """One transaction; commits when the `with connect()` block ends."""

    def __init__(self, raw, postgres: bool):
        self.raw = raw
        self.postgres = postgres

    def execute(self, sql: str, params=()):
        if self.postgres:
            sql = sql.replace("%", "%%").replace("?", "%s")
        return self.raw.execute(sql, tuple(params))

    def insert(self, sql: str, params=()) -> int:
        """Run an INSERT and return the new row's id."""
        return self.execute(sql + " RETURNING id", params).fetchone()["id"]


def _sqlite_ready(path: Path):
    path.parent.mkdir(parents=True, exist_ok=True)

    with sqlite3.connect(path) as raw:
        raw.executescript(SCHEMA.format(**SQLITE_TYPES))
        for table, column, definition in SQLITE_MIGRATIONS:
            existing = {row[1] for row in raw.execute(f"PRAGMA table_info({table})")}
            if column not in existing:
                raw.execute(f"ALTER TABLE {table} ADD COLUMN {column} {definition}")


def _postgres_ready(raw):
    # Several cold-starting instances may get here at once.
    raw.execute("SELECT pg_advisory_xact_lock(724100)")
    raw.execute(SCHEMA.format(**POSTGRES_TYPES))
    raw.commit()


@contextmanager
def connect():
    if is_postgres():
        if psycopg is None:
            raise RuntimeError("DATABASE_URL is set but psycopg isn't installed (pip install psycopg[binary]).")

        # No server-side prepared statements: hosted Postgres usually sits
        # behind a connection pooler (Neon's PgBouncer) that can't keep them.
        raw = psycopg.connect(DATABASE_URL, row_factory=dict_row, connect_timeout=10, prepare_threshold=None)

        with _ready_lock:
            if DATABASE_URL not in _ready:
                _postgres_ready(raw)
                _ready.add(DATABASE_URL)
    else:
        path = Path(DB_PATH)

        with _ready_lock:
            if path not in _ready:
                _sqlite_ready(path)
                _ready.add(path)

        raw = sqlite3.connect(path, timeout=10)
        raw.row_factory = sqlite3.Row
        raw.execute("PRAGMA foreign_keys = ON")

    try:
        yield Connection(raw, is_postgres())
        raw.commit()
    except BaseException:
        raw.rollback()
        raise
    finally:
        raw.close()
